/**
 * Risk flags and anomaly signals for verification cases.
 * These are non-deterministic risk indicators, NOT definitive claims of forgery.
 */

export interface RiskEvaluationInput {
  hasDuplicateFileHash: boolean;
  hasDuplicateRegNumber: boolean;
  metadataCreator?: string | null;
  extractedText?: string | null;
  enteredName: string;
  enteredRegNumber?: string | null;
}

export interface RiskSignalResult {
  hasRiskFlags: boolean;
  flags: string[];
  riskScore: number; // 0.0 (clean) to 1.0 (high risk)
}

const SUSPICIOUS_METADATA_CREATORS = [
  "photoshop",
  "canva",
  "gimp",
  "illustrator",
  "coreldraw",
  "paint.net",
  "inkscape",
  "affinity photo",
];

/**
 * Evaluates document risk signals and returns detected flags with score
 */
export function evaluateRiskSignals(input: RiskEvaluationInput): RiskSignalResult {
  const flags: string[] = [];
  let score = 0.0;

  // 1. Duplicate File Hash
  if (input.hasDuplicateFileHash) {
    flags.push("DUPLICATE_FILE_HASH");
    score += 0.4;
  }

  // 2. Duplicate Registration Number across different users
  if (input.hasDuplicateRegNumber) {
    flags.push("DUPLICATE_REGISTRATION_NUMBER");
    score += 0.4;
  }

  // 3. Document Metadata Anomaly (e.g. PDF generated by photo/graphic editing software)
  if (input.metadataCreator) {
    const creatorLower = input.metadataCreator.toLowerCase();
    const isGraphicEditor = SUSPICIOUS_METADATA_CREATORS.some((tool) =>
      creatorLower.includes(tool)
    );
    if (isGraphicEditor) {
      flags.push("ANOMALOUS_METADATA");
      score += 0.3;
    }
  }

  // 4. Mismatch between entered registration number and OCR extracted text
  if (input.enteredRegNumber && input.extractedText) {
    const cleanReg = input.enteredRegNumber.replace(/[^A-Za-z0-9]/g, "").toUpperCase();
    const cleanExtracted = input.extractedText.replace(/[^A-Za-z0-9]/g, "").toUpperCase();
    if (cleanReg.length >= 4 && !cleanExtracted.includes(cleanReg)) {
      flags.push("FIELD_EXTRACTION_MISMATCH");
      score += 0.2;
    }
  }

  return {
    hasRiskFlags: flags.length > 0,
    flags,
    riskScore: Math.min(1.0, Number(score.toFixed(2))),
  };
}
